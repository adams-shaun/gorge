#!/usr/bin/env bash
# lower-ceilings.sh: lower main's function ceilings to the merged tree's measurement and open (or
# update) one bot pull request (the queue takes it on its fast and lint checks). This is the post-merge half of invariant 8: a
# branch may not lower a shrink-only ratchet (cmd/checkratchet refuses it in lint), so main lowers
# it here, after the merge, where a growth it would race has already landed.
#
# Run from a clean checkout of main with the Go cache warm: the workflow sets GH_TOKEN (a token
# whose pushes start CI; a workflow GITHUB_TOKEN's do not) and calls it daily.
set -uo pipefail
branch=regen/ceilings
file=internal/codeshape/testdata/func_ceilings.tsv

open=$(gh pr list --head "$branch" --state open --json number --jq '.[0].number // empty')
if [ -n "$open" ]; then
	# An open bot PR that still merges and has no failed check is left alone: a push restarts its checks.
	# A red or conflicting one is rebuilt over today's main below, or it would wedge every later run: a
	# branch may grow a function back to the row the bot lowered (green against the old row, red against the
	# bot's), and the bot PR then fails on its merge ref and can never merge.
	state=$(gh pr view "$open" --json mergeable,statusCheckRollup \
		--jq '"\(.mergeable) \([.statusCheckRollup[]? | select((.conclusion // .state // "") | IN("FAILURE","ERROR","TIMED_OUT","STARTUP_FAILURE"))] | length)"') ||
		{ echo "lower-ceilings: gh pr view #$open failed"; exit 1; }
	case "$state" in
	"CONFLICTING "* | *" "[1-9]*) echo "lower-ceilings: #$open is stale or red ($state); rebuilding it over main" ;;
	*) echo "lower-ceilings: #$open is open and green ($state); left alone"; exit 0 ;;
	esac
fi

CODESHAPE_LOWER=1 go test -run '^TestFuncCeilingsLowerOnly$' ./internal/codeshape ||
	{ echo "lower-ceilings: the lowering generator failed"; exit 1; }
if git diff --quiet -- "$file"; then
	echo "lower-ceilings: main's ceilings are at the measurement"
	if [ -n "$open" ]; then
		gh pr close "$open" --comment "Main's ceilings are at the measurement; nothing left to lower." >/dev/null ||
			{ echo "lower-ceilings: closing #$open failed"; exit 1; }
		echo "lower-ceilings: closed #$open"
	fi
	exit 0
fi

git checkout -q -B "$branch" || { echo "lower-ceilings: checkout $branch failed"; exit 1; }
git add -- "$file" || { echo "lower-ceilings: add failed"; exit 1; }
git commit -q -m "codeshape: lower main's function ceilings to the measurement" ||
	{ echo "lower-ceilings: commit failed"; exit 1; }
git push -q -f origin "$branch" || { echo "lower-ceilings: push failed"; exit 1; }
if [ -z "${open:-}" ]; then
	body=$'The shrink-only function ceilings are lowered on main after merge, never in a branch (invariant 8; cmd/checkratchet refuses a lowering pull request), so a lowering cannot race a branch that grows the same function.\n\nGenerated by .github/workflows/ratchet-lower.yml with CODESHAPE_LOWER=1.\n'
	url=$(gh pr create --base main --head "$branch" \
		--title "codeshape: lower main's function ceilings to the measurement" --body "$body") ||
		{ echo "lower-ceilings: gh pr create failed"; exit 1; }
	pr=${url##*/}
	gh api -X POST "repos/{owner}/{repo}/issues/${pr}/labels" -f 'labels[]=queue' >/dev/null ||
		{ echo "lower-ceilings: label failed"; exit 1; }
	echo "lower-ceilings: opened #$pr"
fi
