package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/adams-shaun/gorge/server/gorged"
)

const (
	flagsDocPath  = "../../docs/site/web/flags.md"
	flagsBegin    = "<!-- flags:begin (generated by TestFlagsDocIsCurrent; GORGE_UPDATE_DOCS=1 rewrites it) -->"
	flagsEnd      = "<!-- flags:end -->"
	updateDocsEnv = "GORGE_UPDATE_DOCS"
)

// flagDefaults names the defaults that depend on the machine, so the page states
// the rule instead of the value this machine computed.
var flagDefaults = map[string]string{
	"bot-search-slots": "max(1, GOMAXPROCS/2)",
}

// flagsTable renders this binary's real flag set as a Markdown table, sorted by name.
func flagsTable() string {
	var b strings.Builder
	b.WriteString("| Flag | Default | Meaning |\n|---|---|---|\n")
	gorged.ServeFlagSetFor(extensions()).VisitAll(func(f *flag.Flag) {
		arg, usage := flag.UnquoteUsage(f)
		name := "`-" + f.Name
		if arg != "" && arg != "value" && arg != "string" && arg != "int" && arg != "duration" && arg != "uint" {
			name += " " + arg
		}
		name += "`"
		def := f.DefValue
		if d, ok := flagDefaults[f.Name]; ok {
			def = d
		}
		if def == "" {
			def = "none"
		} else {
			def = "`" + def + "`"
		}
		usage = strings.ReplaceAll(usage, "|", "\\|")
		fmt.Fprintf(&b, "| %s | %s | %s |\n", name, def, usage)
	})
	return b.String()
}

// TestFlagsDocIsCurrent holds docs/site/web/flags.md to the flag set gorged
// parses: the table between the markers is generated from it, so a flag added,
// removed or re-described fails here until the page is regenerated with
// GORGE_UPDATE_DOCS=1 go test ./cmd/gorged -run TestFlagsDocIsCurrent.
func TestFlagsDocIsCurrent(t *testing.T) {
	path := filepath.FromSlash(flagsDocPath)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	page := string(raw)
	i, j := strings.Index(page, flagsBegin), strings.Index(page, flagsEnd)
	if i < 0 || j < i {
		t.Fatalf("%s lacks the %q ... %q markers", flagsDocPath, flagsBegin, flagsEnd)
	}
	want := page[:i+len(flagsBegin)] + "\n\n" + flagsTable() + "\n" + page[j:]
	if want == page {
		return
	}
	if os.Getenv(updateDocsEnv) != "" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Errorf("%s is out of date with gorged's flags; run %s=1 go test ./cmd/gorged -run TestFlagsDocIsCurrent", flagsDocPath, updateDocsEnv)
}
