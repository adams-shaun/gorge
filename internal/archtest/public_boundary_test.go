var (
	generatedTableDir  = regexp.MustCompile(`^cards_[a-z0-9_]+$`)
	generatedTableFile = regexp.MustCompile(`^(card|token)_[a-z0-9_]+\.go$`)
	emailShape         = regexp.MustCompile(`[\w.+-]+@[\w-]+\.[a-z]{2,}`)
	// unresolvableTag matches references a reader of the public tree cannot
	// follow: ticket and phase labels (E3-5, E5-c2, E0), rulings, seat briefs and
	// branch names. Case folds for the operator forms only: "Operator decision" is
	// the same citation. The label form is case-sensitive and starts on a word
	// boundary, so 0xE3, 1E3 and a table id such as e1-r1-s03 stay clean.
	unresolvableTag = regexp.MustCompile(`\bkr-[a-z0-9]|DESIGN §|\bwt/[a-z]|(?i:\(operator\b|operator (ruling|decision))` +
		`|\bE\d+[a-z]?(?:-[a-z0-9]+)?\b|\bRuling [A-Z]-?\d|\bthe brief\b|\bbrief's\b`)
	// sectionCite matches a section sign and the word before it. Only "design §"
	// names a document that crosses with the tree; "spec §4.6", "plan §2" and a
	// bare "§3" name nothing a reader can open.
	sectionCite = regexp.MustCompile(`(\w+)?\s?§\s?\d`)
)

// boundaryRule is one row of the boundary. check returns what it found, or ""
// when path and blob are clean.
type boundaryRule struct {
	id    string
	check func(path string, blob []byte) string
}

var boundaryRules = []boundaryRule{
	{"generated-table-dir", func(p string, _ []byte) string {
		if !inDirac(p) {
			return ""
		}
		for _, dir := range strings.Split(path.Dir(p), "/") {
			if generatedTableDir.MatchString(dir) {
				return "generated card table directory " + dir
			}
		}
		return ""
	}},
	{"kgen-output", func(_ string, blob []byte) string {
		head, ok := bytes.CutPrefix(withoutBOM(blob), []byte("// Code generated by "))
		if !ok {
			return ""
		}
		if line, _, _ := bytes.Cut(head, []byte("\n")); bytes.Contains(line, []byte("kgen")) {
			return "kgen's generated output"
		}
		return ""
	}},
	{"generated-table-file", func(p string, _ []byte) string {
		if inDirac(p) && generatedTableFile.MatchString(path.Base(p)) {
			return "generated card table file"
		}
		return ""
	}},
	{"kgen-report", func(p string, _ []byte) string {
		if base := path.Base(p); inDirac(p) && (base == "OPS.md" || base == "coverage.md") {
			return "kgen's generated report " + base
		}
		return ""
	}},
	{"dirac-binary", func(p string, blob []byte) string {
		if inDirac(p) && isBinary(blob) {
			return "binary file (a NUL byte in its first 8000 bytes)"
		}
		return ""
	}},
	{"forge-script", func(_ string, blob []byte) string {
		b := withoutBOM(blob)
		if bytes.HasPrefix(b, []byte("Name:")) && bytes.Contains(b, []byte("\nOracle:")) {
			return "a Forge card script (GPL-3.0)"
		}
		return ""
	}},
	{"private-fragment", func(_ string, blob []byte) string {
		if isBinary(blob) {
			return ""
		}
		for _, f := range privateFragments {
			if bytes.Contains(blob, []byte(f)) {
				return "private path or host " + strconv.Quote(f)
			}
		}
		return ""
	}},
	{"private-detail", func(p string, blob []byte) string {
		if !inMovedTree(p) || isBinary(blob) {
			return ""
		}
		for _, f := range []string{".ds4/", ".superpowers"} {
			if bytes.Contains(blob, []byte(f)) {
				return "private path " + strconv.Quote(f)
			}
		}
		if m := emailShape.Find(blob); m != nil {
			return "email address " + strconv.Quote(string(m))
		}
		return ""
	}},
	{"private-import", func(p string, blob []byte) string {
		if !strings.HasSuffix(p, ".go") || !bytes.Contains(blob, []byte(privateModule)) {
			return ""
		}
		// The parser sees testdata and build-tag-excluded files alike, and
		// returns what it could read of a file that does not parse.
		f, _ := parser.ParseFile(token.NewFileSet(), p, blob, parser.ImportsOnly)
		if f == nil {
			return ""
		}
		for _, imp := range f.Imports {
			if v, err := strconv.Unquote(imp.Path.Value); err == nil && strings.HasPrefix(v, privateModule) {
				return "imports the private module: " + v
			}
		}
		return ""
	}},
	{"private-require", func(p string, blob []byte) string {
		if (p == "go.mod" || p == "go.work") && bytes.Contains(blob, []byte(privateModule)) {
			return "names the private module"
		}
		return ""
	}},
	{"private-name", func(p string, blob []byte) string {
		if !inMovedTree(p) && !strings.HasPrefix(p, "scripts/kernelbench") {
			return ""
		}
		if !isBinary(blob) && bytes.Contains(blob, []byte(privateName)) {
			return "mentions the private module"
		}
		return ""
	}},
	{"unresolvable-reference", func(p string, blob []byte) string {
		if !inLabelFreeTree(p) || isBinary(blob) {
			return ""
		}
		if m := findUnresolvable(blob); m != nil {
			return "unresolvable reference " + strconv.Quote(string(m))
		}
		return ""
	}},
}

func inDirac(p string) bool     { return strings.HasPrefix(p, "dirac/") }
func inMovedTree(p string) bool { return inDirac(p) || strings.HasPrefix(p, "draft/") }

// inLabelFreeTree is where ticket labels are rejected: the moved trees and the
// draft commands and example that live outside them.
func inLabelFreeTree(p string) bool {
	if inMovedTree(p) {
		return true
	}
	for _, dir := range []string{"cmd/draftsim/", "cmd/labdemo/", "cmd/extagent/", "examples/extagent/"} {
		if strings.HasPrefix(p, dir) {
			return true
		}
	}
	return false
}

// findUnresolvable returns the first reference in blob a reader cannot follow,
// or nil.
func findUnresolvable(blob []byte) []byte {
	if m := unresolvableTag.Find(blob); m != nil {
		return m
	}
	for _, m := range sectionCite.FindAllSubmatch(blob, -1) {
		if string(m[1]) != "design" {
			return m[0]
		}
	}
	return nil
}

func withoutBOM(blob []byte) []byte {
	return bytes.TrimPrefix(blob, []byte("\xef\xbb\xbf"))
}

func isBinary(blob []byte) bool {
	return bytes.IndexByte(blob[:min(len(blob), binaryProbe)], 0) >= 0
}

// publicBoundaryViolations is the boundary's core: one "<rule>: <path>: <what>"
// line for each rule that path and blob break. path is slash-separated and
// relative to the repository root.
func publicBoundaryViolations(path string, blob []byte) []string {
	var out []string
	for _, r := range boundaryRules {
		if what := r.check(path, blob); what != "" {
			out = append(out, r.id+": "+path+": "+what)
		}
	}
	return out
}

// walkPublicFiles reads every tracked file and calls visit with its
// slash-separated repository path. A file deleted from the working tree, a
// symlink and a submodule have no content here to scan. It returns the paths it
// visited.
func walkPublicFiles(t *testing.T, visit func(path string, blob []byte)) map[string]bool {
	t.Helper()
	root := filepath.Join("..", "..")
	cmd := exec.Command("git", "-C", root, "ls-files", "-z", "--cached")
	cmd.Env = cards.GitEnv()
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("git ls-files: %v", err)
	}
	seen := map[string]bool{}
	dirs := map[string]bool{}
	for _, p := range strings.Split(strings.TrimRight(string(out), "\x00"), "\x00") {
		if p == "" || seen[p] {
			continue
		}
		full := filepath.Join(root, filepath.FromSlash(p))
		info, err := os.Lstat(full)
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			t.Fatalf("stat %s: %v", p, err)
		}
		if !info.Mode().IsRegular() {
			continue
		}
		blob, err := os.ReadFile(full)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		seen[p] = true
		visit(p, blob)
		// Lists the parent so the test cache notices a file added beside this one.
		if dir := filepath.Dir(full); !dirs[dir] {
			dirs[dir] = true
			if _, err := os.ReadDir(dir); err != nil {
				t.Fatalf("list %s: %v", dir, err)
			}
		}
	}
	return seen
}

// TestPublicBoundary fails on generated card tables, binaries under dirac/,
// Forge scripts, private paths, imports of the private module and unresolvable
// ticket tags in the moved trees (ADR 0002 decision 6).
func TestPublicBoundary(t *testing.T) {
	var bad []string
	seen := walkPublicFiles(t, func(p string, blob []byte) {
		bad = append(bad, publicBoundaryViolations(p, blob)...)
	})
	if len(seen) < minPublicFiles {
		t.Fatalf("scanned only %d files, fewer than %d: the boundary would run vacuously", len(seen), minPublicFiles)
	}
	for _, must := range []string{"go.mod", "engine/cards/boundary_test.go"} {
		if !seen[must] {
			t.Fatalf("%s is not in the scanned set: the boundary would run vacuously", must)
		}
	}
	sort.Strings(bad)
	if len(bad) > 0 {
		t.Errorf("%d violations of the public boundary (docs/decisions/0002-public-engines-and-draft.md):\n\t%s",
			len(bad), strings.Join(bad, "\n\t"))
	}
}

// forgeLines indexes script lines by their first forgeLineMin bytes, so a
// file's scan costs one map probe per candidate position, not one search per
// script line.
type forgeLines struct {
	n     int
	byKey map[string][]forgeLine
}

type forgeLine struct{ text, script string }

const (
	// forgeLineMin is the shortest script line TestNoVerbatimForgeLines counts. Shorter ones ("K:Flying")
	// are too plain to identify a script.
	forgeLineMin = 30
	// forgeLinesFloor is that test's anti-vacuous floor. The corpus at FORGE_REF has
	// far more distinct long lines than this.
	forgeLinesFloor = 50000
	// forgeVerbatimBaselinePath holds file paths only, sorted, one per line: never
	// any script text.
	forgeVerbatimBaselinePath = "testdata/forge_verbatim_baseline.txt"
	// forgeVerbatimBaselineMax is the baseline's ceiling, which is what makes it
	// shrink-only: lower it when a file leaves the list, never raise it. Only a
	// FORGE_REF bump that puts a line in an existing fixture can justify a raise.
	forgeVerbatimBaselineMax = 487
)

func newForgeLines() *forgeLines { return &forgeLines{byKey: map[string][]forgeLine{}} }

// add records each counted line of one script. A line several scripts share
// keeps the first script that had it.
func (x *forgeLines) add(script string, blob []byte) {
	sc := bufio.NewScanner(bytes.NewReader(blob))
	sc.Buffer(nil, 1<<20)
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), " \t\r")
		if len(line) < forgeLineMin || !isForgeLinePrefix(line) {
			continue
		}
		key := line[:forgeLineMin]
		if slices.ContainsFunc(x.byKey[key], func(l forgeLine) bool { return l.text == line }) {
			continue
		}
		x.byKey[key] = append(x.byKey[key], forgeLine{line, script})
		x.n++
	}
}

func isForgeLinePrefix(line string) bool {
	for _, p := range []string{"A:", "T:", "S:", "R:", "K:", "SVar:"} {
		if strings.HasPrefix(line, p) {
			return true
		}
	}
	return false
}

// find returns the script owning a counted line that occurs in blob as a
// fragment, or "". Every counted line starts with one of a few prefixes ending
// in a colon, so only the positions before a colon can begin a match.
func (x *forgeLines) find(blob []byte) string {
	for i := 0; i < len(blob); {
		j := bytes.IndexByte(blob[i:], ':')
		if j < 0 {
			return ""
		}
		colon := i + j
		i = colon + 1
		start := -1
		switch {
		case colon >= 4 && string(blob[colon-4:colon]) == "SVar":
			start = colon - 4
		case colon >= 1 && strings.IndexByte("ATSRK", blob[colon-1]) >= 0:
			start = colon - 1
		}
		if start < 0 || start+forgeLineMin > len(blob) {
			continue
		}
		for _, l := range x.byKey[string(blob[start:start+forgeLineMin])] {
			if bytes.HasPrefix(blob[start:], []byte(l.text)) {
				return l.script
			}
		}
	}
	return ""
}

// verbatimBaselineProblems compares the files holding a verbatim script line
// with the baseline: dirac/ and draft/ never have one, a new file fails, and a
// listed file that is now clean must leave the list.
func verbatimBaselineProblems(found map[string]string, baseline []string, ceiling int) []string {
	var out []string
	if len(baseline) > ceiling {
		out = append(out, fmt.Sprintf("the baseline has %d files, above its ceiling of %d: it only shrinks", len(baseline), ceiling))
	}
	if !slices.IsSorted(baseline) {
		out = append(out, "the baseline is not sorted")
	}
	listed := map[string]bool{}
	for _, p := range baseline {
		if listed[p] {
			out = append(out, p+": listed twice in the baseline")
		}
		listed[p] = true
		if inMovedTree(p) {
			out = append(out, p+": dirac/ and draft/ have no baseline")
		}
		if _, ok := found[p]; !ok {
			out = append(out, p+": now clean, remove it from the baseline and lower its ceiling")
		}
	}
	for p, script := range found {
		if !listed[p] {
			out = append(out, p+": holds a line of "+script+" verbatim; rewrite the fixture")
		}
	}
	sort.Strings(out)
	return out
}

// TestNoVerbatimForgeLines: no committed file holds a Forge script
// line of 30 or more characters as a fragment. Under dirac/ and draft/ that is
// absolute. Elsewhere existing fixtures are a shrinking
// baseline (forgeVerbatimBaselinePath). Failure messages name the script, never
// the line.
func TestNoVerbatimForgeLines(t *testing.T) {
	corpus, ok := testutil.SharedCorpusDir(".")
	folder := filepath.Join(corpus, "cardsfolder")
	if _, err := os.Stat(folder); !ok || err != nil {
		msg := "TestNoVerbatimForgeLines needs the corpus: no " + folder + "; run make fetch-cards"
		if os.Getenv("CI") != "" {
			t.Fatal(msg)
		}
		t.Skip(msg)
	}
	index := newForgeLines()
	err := filepath.WalkDir(folder, func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() {
			return err
		}
		blob, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		index.add(d.Name(), blob)
		return nil
	})
	if err != nil {
		t.Fatalf("read the corpus: %v", err)
	}
	if index.n < forgeLinesFloor {
		t.Fatalf("the corpus gave only %d script lines, fewer than %d: the scan would run vacuously", index.n, forgeLinesFloor)
	}

	t.Logf("%d distinct script lines of %d or more characters", index.n, forgeLineMin)

	found := map[string]string{}
	walkPublicFiles(t, func(p string, blob []byte) {
		if isBinary(blob) {
			return
		}
		if script := index.find(blob); script != "" {
			found[p] = script
		}
	})

	raw, err := os.ReadFile(filepath.FromSlash(forgeVerbatimBaselinePath))
	if err != nil {
		t.Fatalf("read the baseline: %v", err)
	}
	if bad := verbatimBaselineProblems(found, strings.Fields(string(raw)), forgeVerbatimBaselineMax); len(bad) > 0 {
		t.Errorf("%d problems with verbatim Forge lines (CONTRIBUTING.md, the GPL boundary):\n\t%s", len(bad), strings.Join(bad, "\n\t"))
	}
}

// engineTierEdges lists each dependency the engine tier or server/gorged may not
// have: the engines import no draft or dirac package, and the library gorged
// reaches draft only through the plugin seam cmd/gorged fills.
func engineTierEdges(pkgs map[string]pkg) []string {
	under := func(p, tree string) bool { return p == tree || strings.HasPrefix(p, tree+"/") }
	var out []string
	for path, p := range pkgs {
		for dep := range p.deps {
			switch {
			case under(path, module+"/engine") && (under(dep, module+"/draft") || under(dep, module+"/dirac")),
				path == module+"/server/gorged" && under(dep, module+"/draft"):
				out = append(out, path+" -> "+dep)
			}
		}
	}
	sort.Strings(out)
	return out
}

// TestEngineTierImportsNeitherDraftNorDirac holds the engine tier below both
// trees. A dirac adapter edge into server/ does not break it.
func TestEngineTierImportsNeitherDraftNorDirac(t *testing.T) {
	pkgs := packages(t)
	for _, must := range []string{module + "/engine/rules", module + "/server/gorged"} {
		if _, ok := pkgs[must]; !ok {
			t.Fatalf("%s is not in go list's output: the test would run vacuously", must)
		}
	}
	if bad := engineTierEdges(pkgs); len(bad) > 0 {
		t.Errorf("forbidden dependencies (ADR 0002):\n\t%s", strings.Join(bad, "\n\t"))
	}
}

