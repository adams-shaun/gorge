// valCounterWord is the gorge counter word of a <Name>Counter variant:
// ChargeCounter gives CHARGE.
func valCounterWord(variant string) string {
	return strings.ToUpper(strings.TrimSuffix(variant, "Counter"))
}

// valPTWord spells a +p/+t counter: (1,1) P1P1, (-1,-1) M1M1, (0,1) P0P1.
func valPTWord(p, t int) string {
	one := func(n int) string {
		if n < 0 {
			return fmt.Sprintf("M%d", -n)
		}
		return fmt.Sprintf("P%d", n)
	}
	return one(p) + one(t)
}

func init() {
	for _, name := range valCounterNames {
		w := valCounterWord(name)
		register("CounterType."+name, func(c *Ctx, n node) (any, error) { return w, nil })
	}
	register("CounterType.PTCounter", func(c *Ctx, n node) (any, error) {
		p, okP := intOf(argN(n, 0))
		t, okT := intOf(argN(n, 1))
		if !okP || !okT {
			return nil, fmt.Errorf("cardc: %s: PTCounter wants two numbers", c.Src())
		}
		return valPTWord(p, t), nil
	})
}
