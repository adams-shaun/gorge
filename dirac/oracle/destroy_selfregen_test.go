// TestDestroySelfRegenerateLowers plays Mossbridge Troll's "If CARDNAME would
// be destroyed, regenerate it" (R:Event$ Destroy | ValidCard$ Card.Self |
// Regeneration$ True, lowered as kop.ReplDestroyRegenerate) in lockstep with
// gorge over the destroyregen fixture pool
// (dirac/cardset/pools/fixtures/destroyregen): Murder and Day of Judgment
// destroy it, Typhoid Rats' deathtouch block is the lethal-damage
// state-based path, and Terror and Wrath of God (NoRegen$ True) destroy it
// with no regeneration (gorge replacementMatchesDestroy skips the line,
// CR 701.19c).
//
// Preconditions: the Troll's table carries the replacement (with the lowering
// reverted it is refused and this fails), and the kernel applied the line in
// at least three destructions (DestroyRegenStats). The mutation subtest
// turns the kernel arm off and must diverge.
func TestDestroySelfRegenerateLowers(t *testing.T) {
	if isolate(t) {
		return
	}
	set, err := cardset.RawByName(destroyRegenPool)
	if err != nil {
		t.Fatal(err)
	}
	tbl, _, _, err := set.Matchup(destroyRegenDecks[0][0], destroyRegenDecks[0][1])
	if err != nil {
		t.Fatal(err)
	}
	lowered := false
	for _, cd := range tbl.Cards {
		if cd.Name != "Mossbridge Troll" {
			continue
		}
		for _, a := range cd.Abilities {
			lowered = lowered || a.Kind == kop.AbReplacement && a.Repl.Kind == kop.ReplDestroyRegenerate
		}
	}
	if !lowered {
		t.Fatal("Mossbridge Troll: no ReplDestroyRegenerate in the table (the self-regenerate destroy line is not lowered)")
	}
	t.Run("lockstep", func(t *testing.T) {
		before := dirac.DestroyRegenStats.Hits.Load()
		run := runFixtureLockstep(t, destroyRegenPool, destroyRegenDecks, destroyRegenWatch, 48, true, nil)
		hits := dirac.DestroyRegenStats.Hits.Load() - before
		t.Logf("%d games, %d divergences, %d stalls, casts %v, %d destructions regenerated by the line", run.games, run.divs, run.stalls, run.casts, hits)
		if hits < 3 {
			t.Fatalf("the Troll's destroy line replaced %d destructions (< 3): the pool never reaches it", hits)
		}
	})
	t.Run("mutation", func(t *testing.T) {
		old := dirac.DebugDestroyRegenOff
		dirac.DebugDestroyRegenOff = true
		defer func() { dirac.DebugDestroyRegenOff = old }()
		run := runFixtureLockstep(t, destroyRegenPool, destroyRegenDecks, destroyRegenWatch, 48, false, nil)
		run.requireDivergence(t, "Mossbridge Troll destroyed with its regenerate line off")
	})
}

const destroyRegenPool = "destroyregen"

var destroyRegenWatch = map[string]bool{
	"Mossbridge Troll": true, "Murder": true, "Terror": true, "Day of Judgment": true, "Wrath of God": true,
}

var destroyRegenDecks = []fixtureDecks{{
	{{Name: "Mossbridge Troll", Count: 10}, {Name: "Llanowar Elves", Count: 8}, {Name: "Forest", Count: 22}},
	{
		{Name: "Murder", Count: 4}, {Name: "Terror", Count: 3}, {Name: "Day of Judgment", Count: 3},
		{Name: "Wrath of God", Count: 2}, {Name: "Typhoid Rats", Count: 6},
		{Name: "Swamp", Count: 12}, {Name: "Plains", Count: 10},
	},
}}
