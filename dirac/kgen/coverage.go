package kgen

import (
	"fmt"
	"io"
	"sort"
	"strings"
)

// coverage summarises which decks the generated table fully supports.
type coverage struct {
	decks, supported int
	cards, cardsOK   int
	refused          []refusal
	deckHits         map[string]int // refused card -> decks it blocks
}

func computeCoverage(p *pool, lw *lowered) coverage {
	bad := map[string]bool{}
	cv := coverage{decks: len(p.decks), cards: len(lw.cards), deckHits: map[string]int{}}
	for _, c := range lw.cards {
		if len(c.Refusals) > 0 {
			bad[c.Name] = true
			cv.refused = append(cv.refused, c.Refusals...)
		} else {
			cv.cardsOK++
		}
	}
	for _, d := range p.decks {
		ok := true
		for _, n := range d {
			if bad[n] {
				ok = false
				cv.deckHits[n]++
			}
		}
		if ok {
			cv.supported++
		}
	}
	return cv
}

// writeCoverage writes coverage.md.
func writeCoverage(w io.Writer, pool string, cv coverage) {
	fmt.Fprintf(w, "# kgen coverage: pool %s\n\n", pool)
	fmt.Fprintf(w, "The dirac card table's coverage. Generated by `go run ./dirac/cmd/kgen`; do not edit.\n\n")
	if cv.decks > 0 {
		fmt.Fprintf(w, "- decks fully supported: %d of %d (%.2f%%)\n", cv.supported, cv.decks, 100*float64(cv.supported)/float64(cv.decks))
	}
	fmt.Fprintf(w, "- cards supported: %d of %d\n", cv.cardsOK, cv.cards)
	fmt.Fprintf(w, "- refused cards: %d\n\n", cv.cards-cv.cardsOK)
	if len(cv.refused) == 0 {
		return
	}
	cardList := cv.decks == 0
	if cardList {
		fmt.Fprintf(w, "## Refusals\n\n| card | IR node | reason |\n|---|---|---|\n")
	} else {
		fmt.Fprintf(w, "## Refusals\n\n| card | decks blocked | IR node | reason |\n|---|---|---|---|\n")
	}
	sort.SliceStable(cv.refused, func(i, j int) bool {
		a, b := cv.refused[i], cv.refused[j]
		if cv.deckHits[a.Card] != cv.deckHits[b.Card] {
			return cv.deckHits[a.Card] > cv.deckHits[b.Card]
		}
		if a.Card != b.Card {
			return a.Card < b.Card
		}
		return a.Node < b.Node
	})
	for _, r := range cv.refused {
		if cardList {
			fmt.Fprintf(w, "| %s | %s | %s |\n", r.Card, mdEscape(r.Node), mdEscape(r.Reason))
			continue
		}
		fmt.Fprintf(w, "| %s | %d | %s | %s |\n", r.Card, cv.deckHits[r.Card], mdEscape(r.Node), mdEscape(r.Reason))
	}
	// Refusals by reason class.
	byReason := map[string]int{}
	for _, r := range cv.refused {
		byReason[reasonClass(r.Reason)]++
	}
	var rs []string
	for k := range byReason {
		rs = append(rs, k)
	}
	sort.Strings(rs)
	fmt.Fprintf(w, "\n## Refusals by reason\n\n| reason | count |\n|---|---|\n")
	for _, k := range rs {
		fmt.Fprintf(w, "| %s | %d |\n", mdEscape(k), byReason[k])
	}
	// Refusals by class and tier.
	fmt.Fprintf(w, "\n## Refusals by class and tier\n\n")
	fmt.Fprintf(w, "Tier: G generator-only, K keyword desugaring, O op or predicate arm, M<n> mechanism, ? unclassified. Cards: refused cards carrying the class.\n\n")
	fmt.Fprintf(w, "| class | tier | cards |\n|---|---|---|\n")
	for _, r := range refusalClassRows(cv.refused) {
		fmt.Fprintf(w, "| %s | %s | %d |\n", mdEscape(r.class), r.tier, r.cards)
	}
}

func reasonClass(r string) string {
	if i := strings.Index(r, ":"); i > 0 && strings.HasPrefix(r, "repl-hard") {
		return "repl-hard"
	}
	return r
}

func mdEscape(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
